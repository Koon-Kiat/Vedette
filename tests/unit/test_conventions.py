def test_a_pull_request_that_follows_the_template_passes() -> None:
    assert conventions.check_pull_request("feat(eval): measure injection", BODY, number=7) == []


def test_the_title_limit_leaves_room_for_the_pull_request_number() -> None:
    title = "fix: " + "a" * 62
    assert len(title) == 67
    assert conventions.check_pull_request(title, None, number=7) == []
    problems = conventions.check_pull_request(title, None, number=10)
    assert len(problems) == 1
    assert "shorten it to 66" in problems[0]


def test_the_title_github_cut_short_is_refused() -> None:
    title = "fix: refuse a commit when the secret scan cannot read the staged changes"
    problems = conventions.check_pull_request(title, None, number=5)
    assert len(problems) == 1
    assert "72 characters; shorten it to 67" in problems[0]


def test_a_title_that_is_not_a_conventional_commit_is_refused() -> None:
    problems = conventions.check_pull_request("Measure injection", None, number=7)
    assert len(problems) == 1
    assert "Conventional Commit" in problems[0]


def test_backlog_ids_are_refused_in_the_title_and_the_description() -> None:
    body = BODY.replace("held-out set.\n\n## Changes", "held-out set (AN-2).\n\n## Changes")
    problems = conventions.check_pull_request("fix(eval): close EV-1", body, number=7)
    assert len(problems) == 2
    assert "'EV-1' is an internal backlog id" in problems[0]
    assert "'AN-2' is an internal backlog id" in problems[1]


def test_milestone_codes_and_attribution_are_refused_in_the_description() -> None:
    body = BODY + "\nFinishes M4.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"
    problems = conventions.check_pull_request("feat: x", body, number=7)
    assert len(problems) == 2
    assert any("milestone code" in problem for problem in problems)
    assert any("attribution" in problem for problem in problems)


@pytest.mark.parametrize(
    "extra",
    ["## What leaves your machine", "## After merging", "## Smaller review findings"],
)
def test_sections_beyond_the_template_are_refused(extra: str) -> None:
    problems = conventions.check_pull_request("feat: x", f"{BODY}\n{extra}\n\nText.\n", number=7)
    assert len(problems) == 1
    assert "template's sections" in problems[0]


def test_notes_is_accepted_only_as_the_last_section() -> None:
    assert conventions.check_pull_request("feat: x", f"{BODY}\n## Notes\n\nA.\n", number=7) == []
    early = BODY.replace("## Testing", "## Notes\n\nA.\n\n## Testing")
    assert len(conventions.check_pull_request("feat: x", early, number=7)) == 1


SWAPPED = BODY.replace("## Changes", "## Testing").replace(
    "## Testing\n\n- [x]", "## Changes\n\n- [x]"
)


@pytest.mark.parametrize(
    "body",
    [
        SWAPPED,
        BODY.replace("## Summary", "# Summary"),
        BODY.replace("## Testing\n", ""),
        "",
    ],
    ids=["out of order", "top-level heading", "missing section", "empty"],
)
def test_a_description_without_the_template_sections_is_refused(body: str) -> None:
    problems = conventions.check_pull_request("feat: x", body, number=7)
    assert len(problems) == 1
    assert "template's sections" in problems[0]


def test_subheadings_inside_a_section_are_accepted() -> None:
    body = BODY.replace("- Adds the held-out set.", "### Detection\n\n- Adds the held-out set.")
    assert conventions.check_pull_request("feat: x", body, number=7) == []


LOG = "\x1eabc1234\nfeat: fine\n\n\x1edef5678\nAdd a thing\n\nFinishes M2.\n"


def test_each_commit_in_a_git_log_is_checked() -> None:
    problems = conventions.check_log(LOG)
    assert len(problems) == 2
    assert all(problem.startswith("commit def5678") for problem in problems)


def test_an_empty_git_log_has_no_problems() -> None:
    assert conventions.check_log("") == []


def test_the_hook_entry_point_refuses_a_bad_message_with_status_1(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    message = tmp_path / "COMMIT_EDITMSG"
    message.write_text("Add things\n", encoding="utf-8")
    status, err = _main(monkeypatch, capsys, "commit-msg", str(message))
    assert status == 1
    assert "Conventional Commit" in err


def test_the_hook_entry_point_reads_stdin_and_accepts_a_good_message(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    result = _main(monkeypatch, capsys, "commit-msg", "-", stdin="fix(enrich): keep the root\n")
    assert result == (0, "")


def test_the_commits_entry_point_reads_a_git_log_from_stdin(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    status, err = _main(monkeypatch, capsys, "commits", "-", stdin=LOG)
    assert status == 1
    assert err.count("commit def5678") == 2


def test_the_pull_request_entry_point_checks_the_body_from_stdin(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    args = ("pr", "--number", "7", "--title", "feat: x", "--body-file", "-")
    status, err = _main(monkeypatch, capsys, *args, stdin="Text.")
    assert status == 1
    assert "template's sections" in err
